// TestG인덱스N값 : 인덱스/값 조회 정상 및 에러 케이스.
// 희소_모음의 M저장소 = [5일전, 3일전, 1일전] (인덱스 0, 1, 2)
func TestG인덱스N값(t *testing.T) {
	모음 := f테스트용_희소_모음()

	// G인덱스 : 일자가 저장소에서 몇 번째인지 조회. 3일전 → 인덱스 1
	인덱스, 에러 := 모음.G인덱스(n일전_정수값(3))
	lb.F테스트_에러없음(t, 에러)
	lb.F테스트_같음(t, 인덱스, 1)

	// G값 : 일자(정수)로 레코드 직접 조회. 5일전 레코드 존재
	값, 에러 := 모음.G값(n일전_정수값(5))
	lb.F테스트_에러없음(t, 에러)
	lb.F테스트_같음(t, 값.G일자(), n일전_정수값(5))

	// G값2 : 일자로 레코드 직접 조회. 5일전 레코드 존재
	값2, 에러 := 모음.G값2(n일전(5))
	lb.F테스트_에러없음(t, 에러)
	lb.F테스트_같음(t, 값2.G일자(), n일전_정수값(5))

	// 존재하지 않는 일자(99999999) → 에러
	_, 에러 = 모음.G인덱스(99999999)
	lb.F테스트_에러발생(t, 에러)

	// G값2 : time.Time 기반 조회. 금일 레코드 없음 → 에러
	_, 에러 = 모음.G값2(lb.F금일())
	lb.F테스트_에러발생(t, 에러)
}

// TestG값_모음N최근_값_모음 : 구간 조회 정상 및 에러 케이스.
// 희소_모음의 M저장소 = [5일전, 3일전, 1일전] (인덱스 0, 1, 2)
func TestG값_모음N최근_값_모음(t *testing.T) {
	모음 := f테스트용_희소_모음()

	// G값_모음(시작일, 종료일) : 두 일자 모두 존재해야 하는 닫힌 구간 조회.
	// 5일전~1일전 → [5일전, 3일전, 1일전]
	값_모음, 에러 := 모음.G값_모음(n일전_정수값(5), n일전_정수값(1))
	lb.F테스트_에러없음(t, 에러)
	lb.F테스트_같음(t, len(값_모음), 3)

	// 3일전~1일전 → [3일전, 1일전]
	값_모음, 에러 = 모음.G값_모음(n일전_정수값(3), n일전_정수값(1))
	lb.F테스트_에러없음(t, 에러)
	lb.F테스트_같음(t, len(값_모음), 2)

	// 시작일 > 종료일 → 에러
	_, 에러 = 모음.G값_모음(n일전_정수값(1), n일전_정수값(5))
	lb.F테스트_에러발생(t, 에러)

	// 시작일 존재하지 않음(4일전) → 에러
	_, 에러 = 모음.G값_모음(n일전_정수값(4), n일전_정수값(1))
	lb.F테스트_에러발생(t, 에러)

	// G최근_값_모음(시작일) : 시작일~저장소 마지막까지의 구간 조회.
	// 시작일이 존재하지 않으면 시작일 이후의 첫 레코드부터 반환.
	// 3일전~마지막(1일전) → [3일전, 1일전]
	최근_모음, 에러 := 모음.G최근_값_모음(n일전_정수값(3))
	lb.F테스트_에러없음(t, 에러)
	lb.F테스트_같음(t, len(최근_모음), 2)

	// 시작일 존재하지 않음(4일전) → 시작일 이후의 첫 레코드(3일전)부터 → [3일전, 1일전]
	최근_모음, 에러 = 모음.G최근_값_모음(n일전_정수값(4))
	lb.F테스트_에러없음(t, 에러)
	lb.F테스트_같음(t, len(최근_모음), 2)

	// 모든 레코드가 시작일(금일) 이전 → 반환할 값 없음 → 에러
	_, 에러 = 모음.G최근_값_모음(n일전_정수값(0))
	lb.F테스트_에러발생(t, 에러)
}

