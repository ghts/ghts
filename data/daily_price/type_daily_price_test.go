func n일전(n int) time.Time {
	return lb.F금일().AddDate(0, 0, -n)
}

func n일전_정수값(n int) uint32 {
	return lb.F일자2정수(n일전(n))
}

// f테스트용_가격_모음 : 주어진 종가_모음으로 n일치 모음을 생성 (마지막 레코드는 금일).
// 시가/고가/저가 = 종가-1 / 종가+1 / 종가-2 로 채우고, 음수가 되면 (종가+1)/2 로 올림.
func f테스트용_가격_모음(종가_모음 []int64, 거래량 int64) *S종목별_일일_가격정보_모음 {
	개수 := len(종가_모음)
	일일_모음 := make([]*S일일_가격정보, 개수)

	for i, 종가 := range 종가_모음 {
		하한 := (종가 + 1) / 2 // 음수 방지
		일일_모음[i] = New일일_가격정보(
			"000000",
			n일전(개수-1-i),
			lb.F최대값(종가-1, 하한),
			종가+1,
			lb.F최대값(종가-2, 하한),
			종가,
			거래량,
		)
	}

	모음, 에러 := New종목별_일일_가격정보_모음(일일_모음)
	lb.F확인1(에러)

	return 모음
}

// f테스트용_상승_모음 : 종가가 1,2,...,n 으로 매일 1씩 오르는 n일치 모음.
func f테스트용_상승_모음(n int) *S종목별_일일_가격정보_모음 {
	종가_모음 := make([]int64, n)
	for i := range 종가_모음 {
		종가_모음[i] = int64(i + 1)
	}

	return f테스트용_가격_모음(종가_모음, 1000)
}

// f테스트용_하락_모음 : 종가가 n,...,2,1 로 매일 1씩 내리는 n일치 모음.
func f테스트용_하락_모음(n int) *S종목별_일일_가격정보_모음 {
	종가_모음 := make([]int64, n)
	for i := range 종가_모음 {
		종가_모음[i] = int64(n - i)
	}

	return f테스트용_가격_모음(종가_모음, 1000)
}

// f테스트용_일정_모음 : 종가가 n일 내내 동일한 n일치 모음.
func f테스트용_일정_모음(n int, 종가 int64) *S종목별_일일_가격정보_모음 {
	종가_모음 := make([]int64, n)
	for i := range 종가_모음 {
		종가_모음[i] = 종가
	}

	return f테스트용_가격_모음(종가_모음, 1000)
}

