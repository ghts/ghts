// f테스트용_종가_시리즈 : 종가_모음으로 모음 생성.
// 시가=종가-1, 고가=종가+1, 저가=종가-2, 거래량 일정.
// 종가가 작아 시가/저가가 0 이하가 될 수 있으면 ceil(종가/2)로 하한을 잡는다. (정수)
// 마지막 레코드는 금일.
func f테스트용_종가_시리즈(종가_모음 []int64, 거래량 int64) *S종목별_일일_가격정보_모음 {
	종목코드 := "000000"
	개수 := len(종가_모음)
	일일_모음 := make([]*S일일_가격정보, 개수)

	for i, 종가 := range 종가_모음 {
		하한 := (종가 + 1) / 2 // 음수값 방지
		시가, 저가 := 종가-1, 종가-2
		시가 = lb.F최대값(시가, 하한)
		저가 = lb.F최대값(저가, 하한)
		일일_모음[i] = New일일_가격정보(종목코드, n일전(개수-1-i), 시가, 종가+1, 저가, 종가, 거래량)
	}

	모음, 에러 := New종목별_일일_가격정보_모음(일일_모음)
	lb.F확인1(에러)

	return 모음
}

// f테스트용_상승_시리즈 : 1부터 n까지 등차 증가하는 종가 시리즈.
func f테스트용_상승_시리즈(n int, 거래량 int64) *S종목별_일일_가격정보_모음 {
	종가_모음 := make([]int64, n)
	for i := range 종가_모음 {
		종가_모음[i] = int64(i + 1)
	}

	return f테스트용_종가_시리즈(종가_모음, 거래량)
}

// f테스트용_하락_시리즈 : n부터 1까지 등차 감소하는 종가 시리즈.
func f테스트용_하락_시리즈(n int, 거래량 int64) *S종목별_일일_가격정보_모음 {
	종가_모음 := make([]int64, n)
	for i := range 종가_모음 {
		종가_모음[i] = int64(n - i)
	}

	return f테스트용_종가_시리즈(종가_모음, 거래량)
}

