// Test이동_평균 : SMA, G이전_SMA, EMA, VWMA (손계산 기반 기대값).
func Test이동_평균(t *testing.T) {
	모음 := f테스트용_종가_시리즈([]int64{1, 2, 3, 4}, 10)

	lb.F테스트_같음(t, 3, 모음.SMA(3)) // (2+3+4)/3
	lb.F테스트_같음(t, 2, 모음.G이전_SMA(1, 3))
	lb.F테스트_같음(t, 1.5, 모음.G이전_SMA(2, 3))

	// EMA(3) : 워밍업 [1, 1.5, 2], 승수 0.5 → 4*0.5 + 2*0.5 = 3
	lb.F테스트_같음(t, 3, 모음.EMA(3))

	// VWMA(3) : 종가[1..3] * 거래량[1..3] 가중 → (2+3+4)*10 / (10+10+10) = 3
	lb.F테스트_같음(t, 3, 모음.VWMA(3))

	// 일정 시리즈 : 모든 이동평균(SMA, EMA, VWMA)은 상수값과 같아야 한다.
	종가_모음 := make([]int64, 30)
	for i := range 종가_모음 {
		종가_모음[i] = 100
	}
	상수 := f테스트용_종가_시리즈(종가_모음, 1000)

	lb.F테스트_같음(t, 100, 상수.SMA(10))
	lb.F테스트_같음(t, 100, 상수.EMA(10))

	// VWMA도 상수값과 동일 : 100*10*1000 / (10*1000) = 100
	lb.F테스트_같음(t, 100, 상수.VWMA(10))
}

// Test볼린저_밴드 : G볼린저_밴드, G볼린저_밴드_정보, G볼린저_밴드_폭.
func Test볼린저_밴드(t *testing.T) {
	모음 := f테스트용_종가_시리즈([]int64{1, 2, 3, 4}, 10)
	// len(4) > w(3) → 최근 w(3)개 종가 [2,3,4], 평균 3,
	// 모집단 표준편차 = sqrt(((2-3)^2+(3-3)^2+(4-3)^2)/3) = sqrt(2/3) ≈ 0.8165

	lb.F테스트_참임(t, lb.F오차(모음.G볼린저_밴드(3, 1.5), 4.224744872) < 0.001) // 3 + 1.5*sqrt(2/3)

	중심값, 상한값, 하한값 := 모음.G볼린저_밴드_정보(3, -2, 2) // 배율 역순 입력도 정상 처리
	lb.F테스트_같음(t, 3, 중심값)
	lb.F테스트_참임(t, lb.F오차(상한값, 4.632993162) < 0.001) // 3 + 2*sqrt(2/3)
	lb.F테스트_참임(t, lb.F오차(하한값, 1.367006838) < 0.001) // 3 - 2*sqrt(2/3)

	중심값, 폭 := 모음.G볼린저_밴드_폭(3)
	lb.F테스트_같음(t, 3, 중심값)
	lb.F테스트_참임(t, lb.F오차(폭, 0.816496581) < 0.001) // sqrt(2/3)
}

