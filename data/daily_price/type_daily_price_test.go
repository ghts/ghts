// Test월변동성_데이터_부족 : (S7) 종가 데이터가 부족해도 G월_변동성() 이 panic 없이 동작.
//
//	월 변동성 = 최근 12개 월 수익률(21일 간격)의 표본 표준편차.
//	종가 n개라면 계산 가능한 월 수익률 k = (n-1)/21 (내림).
//
//		n=0,1,21  → k=0 (수익률 없음)             → 0
//		n=22      → k=1 (표본 1개, 표준편차 미계산) → 0
//		n>=43     → k>=2 (k개 월만 계산)            → 상승 계열이면 > 0
func Test월변동성_데이터_부족(t *testing.T) {
	// 종가 0개 : 생성자는 빈 입력을 거부하지만, G기준일_이전_정보_복사본() 등이 실제로 빈 모음을 만들 수 있으므로 리터럴로 직접 생성.
	t.Run("종가_0개", func(t *testing.T) {
		s := &S종목별_일일_가격정보_모음{M저장소: nil, 인덱스: map[uint32]int{}}

		lb.F테스트_같음(t, 0.0, s.G월_변동성())
	})

	for _, n := range []int{1, 21, 22} {
		t.Run(fmt.Sprintf("종가_%d개_0반환", n), func(t *testing.T) {
			lb.F테스트_같음(t, 0.0, f테스트용_상승_모음(n).G월_변동성())
		})
	}

	for _, n := range []int{43, 100, 252, 253} {
		t.Run(fmt.Sprintf("종가_%d개_양수", n), func(t *testing.T) {
			lb.F테스트_참임(t, f테스트용_상승_모음(n).G월_변동성() > 0)
		})
	}
}

