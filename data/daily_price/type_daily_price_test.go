// TestVPCI_N_MFI : 일정/상승/하락 시리즈별 불변값 검증.
func TestVPCI_N_MFI(t *testing.T) {
	종가_모음 := make([]int64, 30)
	for i := range 종가_모음 {
		종가_모음[i] = 100
	}

	// 일정 시리즈 : VPCI 계열 0.
	// VWMA(5) = VWMA(10) = SMA = 100 이므로 VPC = 100-100 = 0
	상수 := f테스트용_종가_시리즈(종가_모음, 1000)
	lb.F테스트_같음(t, 0, 상수.VPCI(5, 10))
	lb.F테스트_같음(t, 0, 상수.G전일_VPCI(5, 10))
	lb.F테스트_같음(t, 0, 상수.VPCIs(5, 10))

	// MFI 계열 0 : 전형주가 불변 → 전일 대비 상승 아님 → 전부 음(-) 돈 흐름, 양(+) 흐름 0
	lb.F테스트_같음(t, 0, 상수.MFI(5))
	lb.F테스트_같음(t, 0, 상수.G전일_MFI(5))
	lb.F테스트_같음(t, 0, 상수.MFIs(5, 3))

	// 상승 시리즈 : MFI 계열 100 (전부 양(+) 돈 흐름, 음(-) 흐름 0)
	상승 := f테스트용_상승_시리즈(30, 1000)
	lb.F테스트_같음(t, 100, 상승.MFI(5))
	lb.F테스트_같음(t, 100, 상승.MFIs(5, 3))
}
