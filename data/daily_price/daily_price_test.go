// Test이동_평균 : SMA, G이전_SMA, EMA, VWMA (손계산 기반 기대값).
func Test이동_평균(t *testing.T) {
	모음 := f테스트용_종가_시리즈([]float64{1, 2, 3, 4}, 10)

	f테스트용_실수_같음(t, 3, 모음.SMA(3)) // (2+3+4)/3
	f테스트용_실수_같음(t, 2, 모음.G이전_SMA(1, 3))
	f테스트용_실수_같음(t, 1.5, 모음.G이전_SMA(2, 3))

	// EMA(3) : 워밍업 [1, 1.5, 2], 승수 0.5 → 4*0.5 + 2*0.5 = 3
	f테스트용_실수_같음(t, 3, 모음.EMA(3))

	// VWMA(3) : 종가[1..3] * 거래량[1..3] 가중 → (2+3+4)*10 / (10+10+10) = 3
	f테스트용_실수_같음(t, 3, 모음.VWMA(3))

	// 일정 시리즈 : 모든 이동평균(SMA, EMA, VWMA)은 상수값과 같아야 한다.
	종가_모음 := make([]float64, 30)
	for i := range 종가_모음 {
		종가_모음[i] = 100
	}
	상수 := f테스트용_종가_시리즈(종가_모음, 1000)

	f테스트용_실수_같음(t, 100, 상수.SMA(10))
	f테스트용_실수_같음(t, 100, 상수.EMA(10))

	// VWMA도 상수값과 동일 : 100*10*1000 / (10*1000) = 100
	f테스트용_실수_같음(t, 100, 상수.VWMA(10))
}

