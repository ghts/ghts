// f테스트용_실수_같음 : 실수 비교 (허용 오차 1e-6).
func f테스트용_실수_같음(t *testing.T, 기대, 실제 float64) {
	t.Helper()

	if math.Abs(기대-실제) > 1e-6 {
		t.Fatalf("기대 '%v', 실제 '%v'", 기대, 실제)
	}
}

// f테스트용_레코드 : OHLCV 값을 명시하는 테스트용 레코드.
// (New일일_가격정보의 40일 검증을 우회하기 위해 생성자 대신 직접 초기화)
func f테스트용_레코드(종목코드 string, offset_일수 int, 시가, 고가, 저가, 종가, 거래량 float64) *S일일_가격정보 {
	s := new(S일일_가격정보)
	s.M종목코드 = 종목코드
	s.M일자 = lb.F일자2정수(lb.F금일().AddDate(0, 0, offset_일수))
	s.M시가 = 시가
	s.M고가 = 고가
	s.M저가 = 저가
	s.M종가 = 종가
	s.M거래량 = 거래량

	return s
}

// f테스트용_종가_시리즈 : 종가_모음으로 모음 생성.
// 시가=종가-1, 고가=종가+1, 저가=종가-2, 거래량 일정. 마지막 레코드는 금일.
func f테스트용_종가_시리즈(종가_모음 []float64, 거래량 float64) *S종목별_일일_가격정보_모음 {
	종목코드 := "000000"
	개수 := len(종가_모음)
	일일_모음 := make([]*S일일_가격정보, 개수)

	for i, 종가 := range 종가_모음 {
		일일_모음[i] = f테스트용_레코드(종목코드, i-개수+1, 종가-1, 종가+1, 종가-2, 종가, 거래량)
	}

	모음, 에러 := New종목별_일일_가격정보_모음(일일_모음)
	lb.F확인1(에러)

	return 모음
}

// f테스트용_상승_시리즈 : 1부터 n까지 등차 증가하는 종가 시리즈.
func f테스트용_상승_시리즈(n int, 거래량 float64) *S종목별_일일_가격정보_모음 {
	종가_모음 := make([]float64, n)
	for i := range 종가_모음 {
		종가_모음[i] = float64(i + 1)
	}

	return f테스트용_종가_시리즈(종가_모음, 거래량)
}

// f테스트용_하락_시리즈 : n부터 1까지 등차 감소하는 종가 시리즈.
func f테스트용_하락_시리즈(n int, 거래량 float64) *S종목별_일일_가격정보_모음 {
	종가_모음 := make([]float64, n)
	for i := range 종가_모음 {
		종가_모음[i] = float64(n - i)
	}

	return f테스트용_종가_시리즈(종가_모음, 거래량)
}

