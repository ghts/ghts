func TestF2수정구분_모음(t *testing.T) {
	// T수정구분 은 서로 다른 단일 비트(2의 거듭제곱)로 정의된 비트마스크이다.
	// F2수정구분_모음 은 int64 비트마스크를 켜진 비트 단위로 분해해 목록으로 반환한다.
	// 분해 결과는 수정구분_ALL 의 순서와 무관하게 정확해야 하며
	// 반환된 목록의 순서는 수정구분_ALL 의 순서(내림차순)를 따른다.

	// 모든 정의 비트를 내림차순으로 나열한 기대 목록(수정구분_ALL 과 동일한 순서).
	전체_내림차순 := []T수정구분{
		P수정구분_불성실공시종목, P수정구분_수정주가, P수정구분_뮤추얼펀드, P수정구분_정리매매종목,
		P수정구분_ETF종목, P수정구분_증거금100퍼센트, P수정구분_종가범위연장, P수정구분_시가범위연장,
		P수정구분_권리중간배당락, P수정구분_중간배당락, P수정구분_CB발동예고, P수정구분_우선주,
		P수정구분_기준가조정, P수정구분_거래정지, P수정구분_투자경고, P수정구분_관리종목,
		P수정구분_기업분할, P수정구분_주식병합, P수정구분_액면병합, P수정구분_액면분할,
		P수정구분_배당락, P수정구분_권리락,
	}
	전체_비트마스크 := T수정구분(0)
	for _, 비트 := range 전체_내림차순 {
		전체_비트마스크 |= 비트
	}

	tests := []struct {
		이름   string
		입력_값 int64
		기대값  []T수정구분
	}{
		// 0 입력은 특별 가드에서 P수정구분_없음 을 반환한다.
		{"영_값은_없음_구분", 0, []T수정구분{P수정구분_없음}},
		// 단일 비트: 최저비트와 최고비트(0x80000000)를 특히 확인 —
		// 최고비트는 int64 로 넓힐 때 부호 없이 2147483648 로 처리되어야 한다.
		{"단일_최저비트_권리락", int64(P수정구분_권리락), []T수정구분{P수정구분_권리락}},
		{"단일_최고비트_불성실공시종목", int64(P수정구분_불성실공시종목), []T수정구분{P수정구분_불성실공시종목}},
		{"단일_중간비트_기준가조정", int64(P수정구분_기준가조정), []T수정구분{P수정구분_기준가조정}},
		// 복합 비트: 0x6 = 액면분할(0x4)+배당락(0x2). 순서가 달라져도 정확히 분해되는지 확인.
		{"복합_0x6_액면분할_배당락", 0x6, []T수정구분{P수정구분_액면분할, P수정구분_배당락}},
		// 높은 비트와 낮은 비트가 혼합돼도 내림차순으로 올바르게 분해됨을 확인.
		{"복합_고저비트_혼합", int64(P수정구분_불성실공시종목 | P수정구분_권리락), []T수정구분{P수정구분_불성실공시종목, P수정구분_권리락}},
		// 모든 정의 비트가 동시에 켜졌을 때 누락·중복 없이 전체를 내림차순으로 반환함을 확인.
		{"전체_정의_비트", int64(전체_비트마스크), 전체_내림차순},
	}

	for _, testcase := range tests {
		t.Run(testcase.이름, func(t *testing.T) {
			실제, 에러 := F2수정구분_모음(testcase.입력_값)
			lb.F테스트_에러없음(t, 에러)
			lb.F테스트_같음(t, 실제, testcase.기대값)
		})
	}
}
