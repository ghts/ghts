package xing

import (
	"strings"
	"testing"

	lb "github.com/ghts/ghts/lib"
	"github.com/ghts/ghts/xing/base"
)

func TestT1410_초저유동성_종목(t *testing.T) {
	시장_구분_모음 := []lb.T시장구분{lb.P시장구분_전체, lb.P시장구분_코스피, lb.P시장구분_코스닥}
	시장_구분 := 시장_구분_모음[lb.F임의_범위_이내_정수값(0, len(시장_구분_모음)-1)]

	종목_구분_모음 := []xt.T초저유동성_질의_구분{xt.P초저유동성, xt.P저PBR}
	종목_구분 := 종목_구분_모음[lb.F임의_범위_이내_정수값(0, len(종목_구분_모음)-1)]

	값_모음, 에러 := TrT1410_초저유동성_조회(시장_구분, 종목_구분)
	lb.F테스트_에러없음(t, 에러)

	for _, 값 := range 값_모음 {
		lb.F테스트_참임(t, F종목코드_존재함(값.M종목코드), 값.M종목코드, 값.M종목명)
		lb.F테스트_다름(t, 값.M종목명, "")

		종목, 에러 := F종목by코드(값.M종목코드)
		lb.F테스트_에러없음(t, 에러)
		lb.F테스트_참임(t, strings.Contains(값.M종목명, 종목.G이름()) ||
			strings.Contains(종목.G이름(), 값.M종목명),
			종목.G이름(), 값.M종목명)

		lb.F테스트_참임(t, 값.M현재가 >= 0)
		lb.F테스트_에러없음(t, 값.M전일대비구분.G검사())
		lb.F테스트_같음(t, 값.M전일대비_등락폭, 값.M전일대비구분.G부호보정_정수64(값.M전일대비_등락폭))
		lb.F테스트_같음(t, 값.M전일대비_등락율, 값.M전일대비구분.G부호보정_실수64(값.M전일대비_등락율))
		lb.F테스트_참임(t, 값.M거래량 >= 0, 값.M종목코드, 값.M종목명, 값.M거래량)
	}
}
