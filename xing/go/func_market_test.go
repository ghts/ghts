package xing

import (
	"testing"

	lb "github.com/ghts/ghts/lib"
)

func TestF종목코드_존재함(t *testing.T) {
	lb.F테스트_참임(t, F종목코드_존재함("069500"))
}

func TestF질의값_종목코드_검사(t *testing.T) {
	질의값1 := lb.New질의값_단일_종목_단순형()
	질의값1.M종목코드 = "069500"

	질의값2 := lb.New질의값_복수_종목(lb.TR조회, "", []string{"069500"})

	lb.F테스트_에러없음(t, F질의값_종목코드_검사(질의값1))
	lb.F테스트_에러없음(t, F질의값_종목코드_검사(질의값2))
}

func TestETF_ETN_종목_여부(t *testing.T) {
	lb.F테스트_거짓임(t, ETF_ETN_종목_여부("000020"))
	lb.F테스트_참임(t, ETF_ETN_종목_여부("069500"))
}

func TestF지주회사_종목_여부(t *testing.T) {
	// 접미사가 없는 지주회사(목록 기준) — 종목 정보 조회 없이 판별.
	lb.F테스트_참임(t, F지주회사_종목_여부("000150")) // 두산
	lb.F테스트_참임(t, F지주회사_종목_여부("000880")) // 한화

	// 종목코드 보정 적용 확인(7자리·접두사 A 제거 후 동일 판별).
	lb.F테스트_참임(t, F지주회사_종목_여부("A000150")) // 보정 → 000150 두산

	// 종목명으로 판별(홀딩스 접미사).
	lb.F테스트_참임(t, F지주회사_종목_여부("000070")) // 삼양홀딩스

	// 지주회사 아닌 종목.
	lb.F테스트_거짓임(t, F지주회사_종목_여부("000020")) // 기아
}
