// TestF실시간_정보_복수_종목_구독_해지 : 여러 종목 코드를 한 번에 구독/해지하는 복수_종목 경로와,
// 시장 구분(코스피/코스닥)에 따라 서로 다른 RT 코드로 분기되는 동작을 확인한다.
func TestF실시간_정보_복수_종목_구독_해지(t *testing.T) {
	if !F당일().Equal(lb.F금일()) || !mt.F한국증시_정규_거래_시간임() {
		t.Skip()
	}

	const 종목코드_코스피 = "005930" // 삼성전자
	const 종목코드_코스닥 = "058470" // 리노공업
	const 종목코드_ETF = "069500" // KODEX 200

	소켓SUB := lb.F확인2(nano.NewNano소켓SUB(xt.F주소_실시간()))
	lb.F대기(lb.P1초)

	th.F테스트_에러없음(t, F실시간_정보_구독_복수_종목(xt.RT코스피_호가_잔량_H1, []string{종목코드_코스피, 종목코드_ETF}))
	th.F테스트_에러없음(t, F실시간_정보_구독_복수_종목(xt.RT코스닥_호가_잔량_HA, []string{종목코드_코스닥}))
	defer func() {
		th.F테스트_에러없음(t, F실시간_정보_해지_복수_종목(xt.RT코스피_호가_잔량_H1, []string{종목코드_코스피, 종목코드_ETF}))
		th.F테스트_에러없음(t, F실시간_정보_해지_복수_종목(xt.RT코스닥_호가_잔량_HA, []string{종목코드_코스닥}))
	}()

	수신_코스피, 수신_코스닥, 수신_ETF := false, false, false

	for range 1000 {
		바이트_변환_모음, 에러 := 소켓SUB.G수신()
		th.F테스트_에러없음(t, 에러)

		i실시간_정보 := lb.F확인2(바이트_변환_모음.S해석기(xt.F바이트_변환값_해석).G해석값(0))

		호가, ok := i실시간_정보.(*xt.S호가_잔량_실시간_정보)
		if !ok {
			continue
		}

		switch 호가.M종목코드 {
		case 종목코드_코스피:
			수신_코스피 = true
		case 종목코드_코스닥:
			수신_코스닥 = true
		case 종목코드_ETF:
			수신_ETF = true
		default:
			continue
		}

		if 수신_코스피 && 수신_코스닥 && 수신_ETF {
			return
		}
	}

	t.FailNow()
}

