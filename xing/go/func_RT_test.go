// TestF주문_응답_실시간_정보_구독_해지 : 주문 응답 실시간 정보의 구독 상태 플래그가
// 구독/해지 호출에 따라 올바르게 토글되는지, 그리고 재구독이 중복 구독 없이 동작하는지 확인한다.
// 테스트 시작 시점(f테스트_준비)에 이미 구독된 상태이므로, 종료 시 다시 구독하여 상태를 복원한다.
func TestF주문_응답_실시간_정보_구독_해지(t *testing.T) {
	if !F당일().Equal(lb.F금일()) || !mt.F한국증시_정규_거래_시간임() {
		t.Skip()
	}

	// 테스트 준비 단계에서 이미 구독되어 있어야 한다.
	th.F테스트_참임(t, 주문_응답_구독_중.G값())

	// 재구독은 중복 구독을 방지하고 에러가 없어야 하며, 상태는 여전히 true여야 한다.
	th.F테스트_에러없음(t, F주문_응답_실시간_정보_구독())
	th.F테스트_참임(t, 주문_응답_구독_중.G값())

	// 해지하면 구독_중 플래그가 false가 된다.
	th.F테스트_에러없음(t, F주문_응답_실시간_정보_해지())
	th.F테스트_거짓임(t, 주문_응답_구독_중.G값())

	// 이후 주문 관련 테스트가 정상 동작하도록 다시 구독하여 상태를 복원한다.
	th.F테스트_에러없음(t, F주문_응답_실시간_정보_구독())
	th.F테스트_참임(t, 주문_응답_구독_중.G값())
}

