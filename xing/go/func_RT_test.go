// TestF실시간_정보_단순TR_구독_해지 : 종목 코드 없이 RT 코드만으로 전체 시장을 구독/해지하는
// 단순TR 경로가 에러 없이 동작하고, 구독된 실시간 데이터가 실제로 수신되는지 확인한다.
func TestF실시간_정보_단순TR_구독_해지(t *testing.T) {
	if !F당일().Equal(lb.F금일()) || !mt.F한국증시_정규_거래_시간임() {
		t.Skip()
	}

	소켓SUB := lb.F확인2(nano.NewNano소켓SUB(xt.F주소_실시간()))
	lb.F대기(lb.P1초)

	th.F테스트_에러없음(t, F실시간_정보_구독_단순TR(xt.RT코스피_호가_잔량_H1))
	defer th.F테스트_에러없음(t, F실시간_정보_해지_단순TR(xt.RT코스피_호가_잔량_H1))

	// 구독된 호가 잔량 데이터가 수신되어야 구독/해지 라운드를 마친다.
	for range 1000 {
		바이트_변환_모음, 에러 := 소켓SUB.G수신()
		th.F테스트_에러없음(t, 에러)

		i실시간_정보 := lb.F확인2(바이트_변환_모음.S해석기(xt.F바이트_변환값_해석).G해석값(0))

		if 호가, ok := i실시간_정보.(*xt.S호가_잔량_실시간_정보); ok {
			th.F테스트_참임(t, 호가.M중간가격 >= 0, 호가.M종목코드)
			return
		}
	}

	t.FailNow()
}

