	th.F테스트_참임(t, 값1.M시가총액 > 0)
	th.F테스트_참임(t, 값1.M배당금 >= 0)
	th.F테스트_참임(t, 값1.M배당수익율 >= 0)
	th.F테스트_참임(t, 값1.M현재가 > 0)
	th.F테스트_참임(t, 값1.M전일종가 > 0)
	th.F테스트_참임(t, 값1.M현재가 > int64(float64(값1.M전일종가)*0.4) || 값1.M현재가 < int64(float64(값1.M전일종가)*1.4))

	값2 := 값.M응답2
	th.F테스트_같음(t, lb.F앞뒤_공백_제거(값2.M종목코드), 종목코드)
