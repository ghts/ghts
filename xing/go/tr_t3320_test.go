	th.F테스트_다름(t, lb.F앞뒤_공백_제거(값1.M한글기업명), "")
	th.F테스트_다름(t, lb.F앞뒤_공백_제거(값1.M본사주소), "")
	th.F테스트_다름(t, lb.F정규식_검색(값1.M본사전화번호, []string{`[1-9]+`}), "")
	th.F테스트_다름(t, lb.F정규식_검색(값1.M최근결산년도, []string{`[1-9]+`}), "")
	th.F테스트_다름(t, lb.F정규식_검색(값1.M결산월, []string{`[1-9]+`}), "")
	th.F테스트_다름(t, lb.F정규식_검색(값1.M최근결산년월, []string{`[1-9]+`}), "")
	th.F테스트_참임(t, 값1.M주당액면가 > 0)
	th.F테스트_참임(t, 값1.M주식수 > 0)
	th.F테스트_다름(t, lb.F앞뒤_공백_제거(값1.M홈페이지), "")
	// M그룹명: 기업그룹에 속하지 않은 기업은 값이 비어있을 수 있어 제외
