	th.F테스트_유효한_숫자(t, 값2.SPS)
	th.F테스트_유효한_숫자(t, 값2.CPS)
	th.F테스트_유효한_숫자(t, 값2.BPS)
	th.F테스트_유효한_숫자(t, 값2.T_PER)
	th.F테스트_유효한_숫자(t, 값2.T_EPS)
	th.F테스트_유효한_숫자(t, 값2.PEG)
	th.F테스트_유효한_숫자(t, 값2.T_PEG)
	th.F테스트_다름(t, lb.F정규식_검색(값2.M최근분기년도, []string{`[1-9]+`}), "")
