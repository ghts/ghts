func TestS종목_UnmarshalBinary_에러_경우(t *testing.T) {
	t.Parallel()

	종목 := New종목with가격정보("005930", "삼성전자", P시장구분_코스피, 50000, 60000, 40000, 51000)
	바이트_모음, 에러 := 종목.MarshalBinary()
	F테스트_에러없음(t, 에러)

	// 비어있는 M값.
	F테스트_에러발생(t, new(S종목).UnmarshalBinary(nil))
	F테스트_에러발생(t, new(S종목).UnmarshalBinary([]byte{}))

	// 너무 짧은 M값 (헤더_길이 5 미만).
	for 길이 := 1; 길이 < 5; 길이++ {
		F테스트_에러발생(t, new(S종목).UnmarshalBinary(바이트_모음[:길이]))
	}

	// 가격_정보가 없는 M값.
	F테스트_에러발생(t, new(S종목).UnmarshalBinary(바이트_모음[:5+6+12]))

	// 여분의 바이트가 있는 M값.
	추가_바이트_모음 := make([]byte, 0, len(바이트_모음)+1)
	추가_바이트_모음 = append(추가_바이트_모음, 바이트_모음...)
	추가_바이트_모음 = append(추가_바이트_모음, 0x00)
	F테스트_에러발생(t, new(S종목).UnmarshalBinary(추가_바이트_모음))

	// 에러 발생 시 필드가 초기화되는지 확인.
	대상 := 종목.G복제본()
	F테스트_에러발생(t, 대상.UnmarshalBinary(바이트_모음[:10]))
	F테스트_같음(t, 대상.G코드(), "")
	F테스트_같음(t, 대상.G이름(), "")
	F테스트_같음(t, 대상.G시장구분(), P시장구분_전체)
	F테스트_같음(t, 대상.G전일_종가(), int64(0))
	F테스트_같음(t, 대상.G상한가(), int64(0))
	F테스트_같음(t, 대상.G하한가(), int64(0))
	F테스트_같음(t, 대상.G기준가(), int64(0))
}

