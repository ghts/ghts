func TestS종목_MarshalBinary(t *testing.T) {
	t.Parallel()

	종목 := New종목with가격정보("005930", "삼성전자", P시장구분_코스피, 50000, 60000, 40000, 51000)

	바이트_모음, 에러 := 종목.MarshalBinary()
	F테스트_에러없음(t, 에러)

	// 포맷 : 시장_구분(1) + 코드_길이(2) + 이름_길이(2) + 코드 + 이름 + 가격_정보(4 x 8바이트, 리틀 엔디언).
	예상_버퍼 := new(bytes.Buffer)
	예상_버퍼.WriteByte(byte(P시장구분_코스피))
	예상_버퍼.Write([]byte{6, 0})  // 코드_길이
	예상_버퍼.Write([]byte{12, 0}) // 이름_길이 (UTF-8)
	예상_버퍼.WriteString("005930")
	예상_버퍼.WriteString("삼성전자")
	예상_버퍼.Write([]byte{0x50, 0xC3, 0, 0, 0, 0, 0, 0}) // 전일_종가 50000
	예상_버퍼.Write([]byte{0x60, 0xEA, 0, 0, 0, 0, 0, 0}) // 상한가 60000
	예상_버퍼.Write([]byte{0x40, 0x9C, 0, 0, 0, 0, 0, 0}) // 하한가 40000
	예상_버퍼.Write([]byte{0x38, 0xC7, 0, 0, 0, 0, 0, 0}) // 기준가 51000

	F테스트_참임(t, bytes.Equal(바이트_모음, 예상_버퍼.Bytes()),
		string(바이트_모음), string(예상_버퍼.Bytes()))
}

