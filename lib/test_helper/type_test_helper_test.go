package th

import (
	"testing"
)

func TestS모의_테스트(t *testing.T) {
	t.Parallel()

	모의_테스트_인터페이스 := *(new(any))
	모의_테스트_인터페이스 = new(S모의_테스트)

	_, ok := 모의_테스트_인터페이스.(testing.TB)
	F테스트_참임(t, ok)

	_, ok = 모의_테스트_인터페이스.(I모의_테스트)
	F테스트_참임(t, ok)

	모의_테스트 := new(S모의_테스트)

	모의_테스트.S모의_테스트_리셋()
	F테스트_거짓임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	모의_테스트.S값(false)
	F테스트_참임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	F테스트_거짓임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	모의_테스트.Error()
	F테스트_참임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	모의_테스트.Errorf("")
	F테스트_참임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	모의_테스트.Fail()
	F테스트_참임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	모의_테스트.FailNow()
	F테스트_참임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	모의_테스트.Fatal()
	F테스트_참임(t, 모의_테스트.Failed())

	모의_테스트.S모의_테스트_리셋()
	모의_테스트.Fatalf("")
	F테스트_참임(t, 모의_테스트.Failed())
}
