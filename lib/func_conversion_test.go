func f자료형_문자열(값 any) string {
	if 값 == nil {
		return "nil"
	}

	자료형 := reflect.TypeOf(값).String()
	시작_인덱스 := strings.Index(자료형, ".") + 1

	return 자료형[시작_인덱스:]
}

