func TestF2실수_소숫점_추가(t *testing.T) {
	t.Parallel()

	테스트_케이스_모음 := []struct {
		이름       string
		값        any
		자릿수      int
		기대_실수값   float64 // 에러 발생을 기대하는 케이스는 무시.
		에러       bool
		에러_포함_문구 string // 검증할 에러 메시지 부분 문자열(선택).
	}{
		// 양수: 기존 동작 유지.
		{"양수", "1234567", 2, 12345.67, false, ""},
		{"양수_자릿수가_N과_같음", "999999", 6, 0.999999, false, ""},
		{"공백은_제거됨", " 1234567 ", 2, 12345.67, false, ""},

		// 음수: 부호를 제외한 자릿수로 검증하고 소숫점을 삽입한다.
		{"음수_자릿수가_충분함", "-1234567", 6, -1.234567, false, ""},
		{"음수_자릿수가_N과_같음", "-999999", 6, -0.999999, false, ""}, // '-.999999' 형태도 유효 문법.
		{"음수_소숫점_2자리", "-50", 2, -0.5, false, ""},

		// 음수: 부호를 제외한 자릿수가 N 미만이면 양수와 동일하게 길이 검증 에러.
		{"음수_자릿수_N-1", "-50000", 6, 0, true, "짧습니다"}, // 수정 전에는 '.-50000' 파싱 실패 에러가 발생.
		{"음수_자릿수_N-2", "-1234", 6, 0, true, "짧습니다"},

		// 도트가 있으면 길이 검증 없이 그대로 사용.
		{"도트_있음", "1234567.89", 2, 1234567.89, false, ""},
		{"도트_있음_짧은길이", "0.123", 6, 0.123, false, ""},

		// 빈 문자열: 길이 검증 에러.
		{"빈문자열", "", 6, 0, true, "짧습니다"},
	}

	for _, 케이스 := range 테스트_케이스_모음 {
		t.Run(케이스.이름, func(t *testing.T) {
			실수값, 에러 := F2실수_소숫점_추가(케이스.값, 케이스.자릿수)

			if 케이스.에러 {
				F테스트_에러발생(t, 에러)
				if 케이스.에러_포함_문구 != "" {
					F테스트_참임(t, strings.Contains(에러.Error(), 케이스.에러_포함_문구), 에러)
				}

				return
			}

			F테스트_에러없음(t, 에러)
			F테스트_같음(t, 실수값, 케이스.기대_실수값)
		})
	}
}

