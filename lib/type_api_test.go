// Tests전송_권한_대기_중_잠금_해제됨 : G획득()이 송신 제한으로 인해 대기하는
// 동안에도 잠금이 해제되어 같은 TR코드의 다른 고루틴이 G남은_수량() 등에 접근할
// 수 있음을 검증한다.
// 과거 구현에서는 대기 내내 잠금을 쥐어 다른 고루틴을 최대 10분간 막았다.
// 아울러 G획득()이 재잠금 후 데드락 없이 정상 종료됨도 함께 확인한다.
func Test전송_권한_대기_중_잠금_해제됨(t *testing.T) {
	t.Parallel()

	// 수량 1, 약 1.1초 (S수량_간격_변경이 100ms를 추가로 더함).
	권한 := New전송_권한("테스트_대기중_잠금해제", 1, P1초).(*s전송_권한)

	// 다음 G획득()이 반드시 대기해야 하는 상태로 만든다.
	권한.전송_기록_저장소.PushBack(F지금())

	// A: G획득()은 창구가 가득 차서 창구 시간만큼 대기한다.
	A완료 := make(chan struct{})
	go func() {
		권한.G획득()
		close(A완료)
	}()

	// A가 대기에 진입할 시간을 조금 준다.
	F대기(P100밀리초)

	// B: 대기 중이어도 G남은_수량()은 지체 없이 돌아와야 한다.
	시작_시간 := F지금()
	권한.G남은_수량()
	대기_시간 := F지금().Sub(시작_시간)

	const 지연_한도 = P300밀리초
	if 대기_시간 > 지연_한도 {
		t.Fatalf("G획득() 대기 중인데 G남은_수량()이 %v 지체됨 (허용 %v). 대기 중 잠금이 해제되어야 한다.", 대기_시간, 지연_한도)
	}

	// G획득() 자체가 재잠금 후 데드락 없이 종료되어야 한다.
	select {
	case <-A완료:
	case <-time.After(P5초):
		t.Fatal("G획득()이 대기 후에도 종료되지 않음. 재잠금 과정에서 데드락이 발생한 것 같다.")
	}
}
