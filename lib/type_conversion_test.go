// TestS바이트_변환_모음_범위_외_인덱스 : 범위 밖 인덱스로 접근하면 패닉 또는 에러가 발생해야 한다.
func TestS바이트_변환_모음_범위_외_인덱스(t *testing.T) {
	t.Parallel()

	변환_모음, 에러 := New바이트_변환_모음(P변환형식_기본값, 100)
	F테스트_에러없음(t, 에러)

	F테스트_패닉_발생(t, func() { _ = 변환_모음.G변환_형식(-1) })
	F테스트_패닉_발생(t, func() { _ = 변환_모음.G변환_형식(변환_모음.G수량()) })

	F테스트_패닉_발생(t, func() { _ = 변환_모음.G자료형_문자열(-1) })
	F테스트_패닉_발생(t, func() { _ = 변환_모음.G자료형_문자열(변환_모음.G수량()) })

	var 값 int
	에러 = 변환_모음.G값(-1, &값)
	F테스트_에러발생(t, 에러, "음수 인덱스에 에러가 발생하지 않았습니다.")

	에러 = 변환_모음.G값(변환_모음.G수량(), &값)
	F테스트_에러발생(t, 에러, "범위 밖 인덱스에 에러가 발생하지 않았습니다.")

	F테스트_에러없음(t, 변환_모음.G값(0, &값))
	F테스트_같음(t, 값, 100)
}

