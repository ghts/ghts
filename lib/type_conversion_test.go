// TestS바이트_변환_모음_UnmarshalBinary_꼬리_바이트 : 마지막 요소 이후에 남은 바이트가 있으면 에러가 발생해야 한다.
func TestS바이트_변환_모음_UnmarshalBinary_꼬리_바이트(t *testing.T) {
	t.Parallel()

	매개체, 에러 := New바이트_변환_모음(P변환형식_기본값, 100)
	F테스트_에러없음(t, 에러)

	바이트_모음, 에러 := 매개체.MarshalBinary()
	F테스트_에러없음(t, 에러)

	꼬리_바이트_추가 := append(append([]byte{}, 바이트_모음...), 0xFF, 0xFF, 0xFF)

	에러 = new(S바이트_변환_모음).UnmarshalBinary(꼬리_바이트_추가)
	F테스트_에러발생(t, 에러, "꼬리 바이트가 남아도는데 에러가 발생하지 않았습니다.")
}

