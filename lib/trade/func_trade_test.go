package trade

import (
	"testing"

	lb "github.com/ghts/ghts/lib"
)

func TestF와일더_이동_평균_입력_검증(t *testing.T) {
	t.Parallel()

	오차_허용범위 := float64(1e-9)
	값_모음 := []float64{1, 2, 3, 4, 5}

	// 무효한 윈도우_크기 → 패닉
	lb.F테스트_패닉_발생(t, func() { _ = F와일더_이동_평균(값_모음, 0) })
	lb.F테스트_패닉_발생(t, func() { _ = F와일더_이동_평균(값_모음, -3) })

	// 비어있는 입력 → 패닉
	lb.F테스트_패닉_발생(t, func() { _ = F와일더_이동_평균([]float64{}, 14) })

	// w=3 : 인덱스 0~2는 확장 윈도우 평균(워밍업), 인덱스 3 이후는 Wilder 평활화.
	//   [0] = 1/1
	//   [1] = (1+2)/2
	//   [2] = (1+2+3)/3
	//   [3] = (2*(3-1)+4)/3 = 8/3
	//   [4] = ((8/3)*(3-1)+5)/3 = 31/9
	결과_모음 := F와일더_이동_평균(값_모음, 3)
	lb.F테스트_같음(t, len(결과_모음), len(값_모음))
	lb.F테스트_참임(t, lb.F오차(결과_모음[0], 1.0) <= 오차_허용범위, 결과_모음)
	lb.F테스트_참임(t, lb.F오차(결과_모음[1], 1.5) <= 오차_허용범위, 결과_모음)
	lb.F테스트_참임(t, lb.F오차(결과_모음[2], 2.0) <= 오차_허용범위, 결과_모음)
	lb.F테스트_참임(t, lb.F오차(결과_모음[3], 8.0/3.0) <= 오차_허용범위, 결과_모음)
	lb.F테스트_참임(t, lb.F오차(결과_모음[4], 31.0/9.0) <= 오차_허용범위, 결과_모음)

	// w=1 : 평활화 없이 원본 입력과 동일.
	결과_모음 = F와일더_이동_평균(값_모음, 1)
	for i := range 값_모음 {
		lb.F테스트_참임(t, lb.F오차(결과_모음[i], 값_모음[i]) <= 오차_허용범위, 결과_모음)
	}

	// w >= len : len으로 클램프 → 전체 입력의 확장 윈도우 평균(최종값 = 전체 평균).
	결과_모음 = F와일더_이동_평균(값_모음, 100)
	lb.F테스트_같음(t, len(결과_모음), len(값_모음))
	lb.F테스트_참임(t, lb.F오차(결과_모음[4], 3.0) <= 오차_허용범위, 결과_모음)
}
